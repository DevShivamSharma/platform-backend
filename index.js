  const authUserValue = adminAuthUserId
    ? `'${escapeSqlLiteral(adminAuthUserId)}'::uuid`
    : "null";

  await runSupabaseSql(
    ref,
    `
insert into organizations (id, name)
values ('${organizationId}'::uuid, '${companyName}')
on conflict (id) do nothing;

insert into organization_users
  (auth_user_id, first_name, last_name, email, organization_id, role, status, account_ids, accounts, is_acknowledged, subscription_id)
values
  (${authUserValue}, 'Admin', 'User', '${safeAdminEmail}', '${organizationId}'::uuid, 'Organization Admin', 'Active', '[]'::jsonb, '[]'::jsonb, true, null)
on conflict (email) do update set
  auth_user_id = excluded.auth_user_id,
  organization_id = excluded.organization_id,
  role = excluded.role,
  status = excluded.status,
  updated_at = now();

update organization_users ou
   set auth_user_id = au.id
  from auth.users au
 where au.email = ou.email
   and ou.email = '${safeAdminEmail}'
   and ou.auth_user_id is null;
`
  );
