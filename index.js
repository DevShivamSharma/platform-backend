// Vercel API helper — thin wrapper that handles auth, team scoping, errors.
// ---------------------------------------------------------------------------
const VERCEL_API = "https://api.vercel.com";

async function vercelFetch(pathStr, { method = "GET", body, token, teamId } = {}) {
  const url = new URL(VERCEL_API + pathStr);
  if (teamId) url.searchParams.set("teamId", teamId);

  const res = await fetch(url, {
    method,
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json",
    },
    body: body ? JSON.stringify(body) : undefined,
  });

  const data = await res.json().catch(() => ({}));
  if (!res.ok) {
    const err = new Error(data?.error?.message || `Vercel API ${res.status}`);
    err.status = res.status;
    err.code = data?.error?.code;
    err.data = data;
    throw err;
  }
  return data;
}

