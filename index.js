function portalAdminSystemSchemaSql() {
  return `
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

CREATE TABLE IF NOT EXISTS organizations (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

CREATE TABLE IF NOT EXISTS organization_users (
  id                        uuid primary key default gen_random_uuid(),
  auth_user_id              uuid unique,
  first_name                text default '',
  last_name                 text default '',
  email                     text not null unique,
  phone_number              text default '',
  country_code              text default '+1',
  organization_id           uuid references organizations(id) on delete cascade,
  role                      text not null default 'Organization User',
  status                    text not null default 'Active',
  account_ids               jsonb not null default '[]',
  accounts                  jsonb not null default '[]',
  is_acknowledged           boolean not null default true,
  is_two_factor_enabled     boolean not null default false,
  requires_password_change  boolean not null default false,
  subscription_id           text,
  profile_photo_url         text default '',
  created_at                timestamptz not null default now(),
  updated_at                timestamptz not null default now()
);

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['organizations','organization_users']
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY;', t);
    EXECUTE format('DROP POLICY IF EXISTS "authenticated_system_access" ON %I;', t);
    EXECUTE format(
      'CREATE POLICY "authenticated_system_access" ON %I FOR ALL TO authenticated USING (true) WITH CHECK (true);', t
    );
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I TO authenticated;', t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I TO service_role;', t);
  END LOOP;
END $$;
`.trim();
}

