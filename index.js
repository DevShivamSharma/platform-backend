function healthIsReady(data) {
  if (!data) return false;
  if (data.status === "ACTIVE_HEALTHY") return true;
  if (Array.isArray(data)) {
    return data.length > 0 && data.every((item) => item.status === "ACTIVE_HEALTHY");
  }
  if (Array.isArray(data.services)) {
    return data.services.every((item) => item.status === "ACTIVE_HEALTHY");
  }
  return Object.values(data).some((value) => value === "ACTIVE_HEALTHY");
}

async function waitForSupabaseHealthy(ref) {
  const startedAt = Date.now();
  let lastStatus = "UNKNOWN";

  while (Date.now() - startedAt < 120_000) {
    try {
      const health = await supabaseManagementFetch(`/v1/projects/${ref}/health`);
      if (healthIsReady(health)) return health;
      lastStatus = JSON.stringify(health);
    } catch (error) {
      const project = await supabaseManagementFetch(`/v1/projects/${ref}`);
      if (project.status === "ACTIVE_HEALTHY") return project;
      lastStatus = project.status || error.message;
    }
    await delay(5000);
  }

  throw new Error(`Supabase project did not become ACTIVE_HEALTHY within 120 seconds. Last status: ${lastStatus}`);
}

function extractSupabaseKey(keys, candidates) {
  const list = Array.isArray(keys)
    ? keys
    : keys.api_keys || keys.keys || keys.data || [];

  const match = list.find((item) => {
    const haystack = `${item.name || ""} ${item.type || ""} ${item.role || ""}`.toLowerCase();
    return candidates.some((candidate) => haystack.includes(candidate));
  });

  return (
    match?.api_key ||
    match?.key ||
    match?.value ||
    match?.secret ||
    match?.token ||
    ""
  );
}

async function getSupabaseApiKeys(ref) {
  const keys = await supabaseManagementFetch(`/v1/projects/${ref}/api-keys?reveal=true`);
  const anonKey = extractSupabaseKey(keys, ["anon", "publishable"]);
  const serviceRoleKey = extractSupabaseKey(keys, ["service_role", "secret"]);
  const supabaseUrl = keys.supabase_url || keys.url || `https://${ref}.supabase.co`;

  if (!anonKey || !serviceRoleKey) {
    throw new Error("Could not extract Supabase anon/publishable and service_role/secret keys.");
  }

  return { supabaseUrl, anonKey, serviceRoleKey };
}

