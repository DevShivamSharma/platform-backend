// POST /api/push
// Body: { projectName, repoName?, private? (default true), description? }
// 1) Validate token + project dir exist
// 2) Ensure .gitignore
// 3) Create GitHub repo for authenticated user
// 4) git init -> add -> commit -> push to origin/main
// ---------------------------------------------------------------------------
app.post("/api/push", async (req, res) => {
  const { projectName, repoName, description, private: isPrivate = true } = req.body || {};
  console.log("\n[push] request:", { projectName, repoName, isPrivate });

  // --- Token check first; everything else depends on it. ---
  const token = process.env.GITHUB_TOKEN;
  if (!token) {
    console.error("[push] GITHUB_TOKEN missing from environment");
    return res.status(500).json({
      success: false,
      error: "Server missing GITHUB_TOKEN. Set it in server/.env. See .env.example.",
    });
  }

  // --- Input validation ---
  if (!projectName || !NAME_RE.test(projectName)) {
    return res.status(400).json({ success: false, error: "projectName missing or invalid" });
  }
  const finalRepoName = (repoName || projectName).trim();
  if (!NAME_RE.test(finalRepoName)) {
    return res.status(400).json({ success: false, error: "repoName must be alphanumeric, dash, or underscore" });
  }

  const destDir = path.join(OUTPUT_DIR, projectName);
  if (!(await fs.pathExists(destDir))) {
    return res.status(404).json({ success: false, error: `Project "${projectName}" not found in output/` });
  }

  try {
    // --- 1. Write .gitignore (won't overwrite an existing one) ---
    const gitignorePath = path.join(destDir, ".gitignore");
    if (!(await fs.pathExists(gitignorePath))) {
      console.log("[push] writing .gitignore");
      await fs.outputFile(gitignorePath, DEFAULT_GITIGNORE);
    } else {
      console.log("[push] .gitignore already present, leaving it");
    }

    // --- 2. Resolve GitHub user via Octokit ---
    const octokit = new Octokit({ auth: token });
    console.log("[push] auth -> getAuthenticatedUser");
    const { data: user } = await octokit.rest.users.getAuthenticated();
    console.log("[push] authenticated as:", user.login);

    // --- 3. Create repo on GitHub ---
    console.log("[push] creating repo:", finalRepoName, "(private:", isPrivate, ")");
    let repo;
    try {
      const created = await octokit.rest.repos.createForAuthenticatedUser({
        name: finalRepoName,
        description: description || `Generated by platform scaffolder.`,
        private: !!isPrivate,
        auto_init: false,
      });
      repo = created.data;
    } catch (err) {
      // Most common: 422 — repo already exists for this user.
      if (err instanceof RequestError && err.status === 422) {
        return res.status(409).json({
          success: false,
          error: `GitHub repo "${user.login}/${finalRepoName}" already exists. Pick a different name.`,
        });
      }
      throw err;
    }
    console.log("[push] repo created:", repo.html_url);

    // --- 4. git init / add / commit / push ---
    const git = simpleGit(destDir);
    const alreadyRepo = await fs.pathExists(path.join(destDir, ".git"));
    if (!alreadyRepo) {
      console.log("[push] git init");
      await git.init();
    } else {
      console.log("[push] .git already exists, reusing");
    }

    // Set local identity so the commit doesn't fail on machines without global config.
    await git.addConfig("user.email", `${user.id}+${user.login}@users.noreply.github.com`, false, "local");
    await git.addConfig("user.name", user.login, false, "local");

    console.log("[push] staging files");
    await git.add(".");

    console.log("[push] committing");
    await git.commit("Initial commit from platform scaffolder");

    // Force branch name to main for consistency.
    await git.branch(["-M", "main"]);

    // Auth the remote URL with the token. Stored only in this local repo's config.
    const authedUrl = repo.clone_url.replace(
      "https://",
      `https://x-access-token:${token}@`
    );

    // If we reused an existing .git, the remote may already exist — replace it.
    const remotes = await git.getRemotes(true);
    if (remotes.find((r) => r.name === "origin")) {
      await git.removeRemote("origin");
    }
    await git.addRemote("origin", authedUrl);

    console.log("[push] pushing to origin/main");
    await git.push(["-u", "origin", "main"]);

    console.log("[push] done:", repo.html_url);
    return res.json({
      success: true,
      repoUrl: repo.html_url,
      cloneUrl: repo.clone_url,
      owner: user.login,
      repoName: finalRepoName,
      message: `Pushed to ${repo.html_url}`,
    });
  } catch (err) {
    console.error("[push] error:", err);
    // simple-git wraps shell errors; surface what we can.
    const detail = err?.message || "Unknown error during push.";
    return res.status(500).json({ success: false, error: detail });
  }
});

