  if (!NAME_RE.test(projectName) || !resolvedTemplateId) {
    return res.status(400).json({
      success: false,
      error: "templateId and projectName must be alphanumeric, dash, or underscore only",
    });
  }

  const srcDir = path.join(TEMPLATES_DIR, resolvedTemplateId);
  const destDir = path.join(OUTPUT_DIR, projectName);

  try {
    console.log("[generate] validating template at:", srcDir);
    if (!(await fs.pathExists(srcDir))) {
      return res.status(404).json({ success: false, error: `Template "${templateId}" not found in templates/` });
    }

    if (await fs.pathExists(destDir)) {
      return res.status(409).json({ success: false, error: `Output "${projectName}" already exists. Pick a different name.` });
    }

    await fs.ensureDir(OUTPUT_DIR);

    console.log("[generate] copying template ->", destDir);
    await fs.copy(srcDir, destDir, {
      filter: (src) => {
        const base = path.basename(src);
        if (EXCLUDED.has(base)) {
          console.log("[generate]   skip:", path.relative(srcDir, src) || base);
          return false;
        }
        return true;
      },
    });

    // KEY CHANGE: when a config is provided, write it directly into the copied
    // template — the config BECOMES the single swappable file that template
    // renders from. Which file depends on the template family:
    //   - landing*  -> src/content.json      (validated portfolio content)
    //   - portal*   -> src/portal-config.json (config-driven admin portal)
    // If no config is provided, the template's bundled default file is kept.
    let generateWarnings = [];
    const isPortal = isPortalConfigTemplate(resolvedTemplateId);

    if (config && typeof config === "object") {
      if (isPortal) {
        // Portal config is written as-is (the template normalises it at runtime
        // via src/config.js). No portfolio validation applies here.
        let configToWrite = config;
        if (isCrudPortalTemplate(resolvedTemplateId)) {
          const normalizedConfig = normalizePortalConfig({
            ...config,
            templateId: resolvedTemplateId,
          });
          normalizedConfig.modules = normalizedConfig.modules.map((module) => ({
            ...module,
            tableName: tableNameForModule(module),
          }));
          configToWrite = resolvedTemplateId === TOPBAR_TEMPLATE_ID
            ? buildTopbarRuntimeConfig(normalizedConfig)
            : await buildPortalAdminRuntimeConfig(normalizedConfig);
        }
        const portalConfigPath = path.join(destDir, "src", "portal-config.json");
        console.log(
          "[generate] Writing portal-config.json, appName:",
          configToWrite?.appName || configToWrite?.branding?.appName,
          "generatedModules:",
          Array.isArray(configToWrite?.generatedModules) ? configToWrite.generatedModules.length : 0
        );
        await fs.writeFile(portalConfigPath, JSON.stringify(configToWrite, null, 2));
        if (isCrudPortalTemplate(resolvedTemplateId)) {
          await writeCrudPortalSupabaseArtifacts(destDir, configToWrite);
        }
      } else {
        // Landing templates: validate + write content.json (existing behaviour).
        const contentPath = path.join(destDir, "src", "content.json");
        const { config: validatedConfig, warnings } = validatePortfolioConfigWithWarnings(config);
        generateWarnings = warnings;
        console.log(
          "[generate] Writing content.json, siteName:",
          validatedConfig.siteName,
          "firstName:",
          validatedConfig.profile?.firstName
        );
        await fs.writeFile(contentPath, JSON.stringify(validatedConfig, null, 2));
      }
    } else {
      console.log(
        `[generate] no config -> keeping template default ${
          isPortal ? "portal-config.json" : "content.json"
        }`
      );
    }

    console.log("[generate] done:", destDir);
    return res.json({
      success: true,
      projectName,
      path: destDir,
      warnings: generateWarnings,
      templateId: resolvedTemplateId,
      requestedTemplateId: templateId,
      message: `Project "${projectName}" generated from template "${resolvedTemplateId}".`,
    });
  } catch (err) {
    console.error("[generate] error:", err);
    return res.status(500).json({ success: false, error: err.message || "Unknown server error" });
  }
