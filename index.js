async function resolveSupabaseOrganizationIdentifier() {
  if (process.env.SUPABASE_ORG_SLUG) {
    return { organization_slug: process.env.SUPABASE_ORG_SLUG };
  }

  const orgId = process.env.SUPABASE_ORG_ID;
  let match;
  try {
    const organizations = await supabaseManagementFetch("/v1/organizations");
    const list = Array.isArray(organizations)
      ? organizations
      : organizations.organizations || organizations.data || [];
    match = list.find((org) => org.id === orgId || org.slug === orgId);
  } catch (error) {
    console.warn("[portal/provision] could not resolve Supabase org slug, falling back to organization_id:", error.message);
  }

  if (match?.slug) {
    return { organization_slug: match.slug };
  }
  return { organization_id: orgId };
}

