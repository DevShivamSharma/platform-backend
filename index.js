// Force PostgREST to reload its schema cache so freshly created tables/columns are
// usable via the REST API. `NOTIFY pgrst, 'reload schema'` is fire-and-forget: on a
// just-created project PostgREST may not be LISTENing yet, so a single NOTIFY can be
// silently dropped and the cache never refreshes (root cause of the recurring
// "Could not find the '<col>' column ... in the schema cache" errors). We therefore
// run it as a dedicated step, a moment after DDL, and retry a few times.
async function reloadPostgrestSchema(ref, { attempts = 4, gapMs = 2500 } = {}) {
  for (let i = 0; i < attempts; i += 1) {
    await delay(gapMs);
    try {
      await runSupabaseSql(ref, "NOTIFY pgrst, 'reload schema';");
    } catch {
      // best-effort; keep retrying
    }
  }
}

