// Call Gemini once and return the parsed JSON object (throws on parse failure).
async function callGemini(ai, description, { retry = false } = {}) {
  const userText = retry
    ? `Your previous output was not valid JSON. Output ONLY valid JSON.\n\nDescription:\n${description}`
    : description;

  const response = await ai.models.generateContent({
    model: "gemini-2.5-flash",
    contents: userText,
    config: {
      systemInstruction: PORTFOLIO_SYSTEM_PROMPT,
      responseMimeType: "application/json",
    },
  });

  const text = response.text ?? "";
  return JSON.parse(text); // may throw -> caller decides retry vs 500
}

