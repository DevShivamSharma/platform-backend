function normalizeTemplateKey(templateId) {
  return String(templateId || "")
    .trim()
    .toLowerCase()
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ");
}

function resolveTemplateId(templateId) {
  const raw = String(templateId || "").trim();
  const normalized = normalizeTemplateKey(raw);
  return TEMPLATE_ALIASES.get(normalized) || TEMPLATE_ALIASES.get(raw.toLowerCase()) || raw;
}

function isCrudPortalTemplate(templateId) {
  return CRUD_PORTAL_TEMPLATE_IDS.has(templateId);
}

function isPortalConfigTemplate(templateId) {
  return isCrudPortalTemplate(templateId) || String(templateId || "").startsWith("portal");
}

function validateResolvedTemplateId(templateId) {
  const resolvedTemplateId = resolveTemplateId(templateId);
  return NAME_RE.test(resolvedTemplateId) ? resolvedTemplateId : "";
}

