async function pushGeneratedProject({ projectName, repoName, description, isPrivate = true }) {
  const token = process.env.GITHUB_TOKEN;
  if (!token) {
    throw new Error("Server missing GITHUB_TOKEN. Set it in server/.env.");
  }

  const finalRepoName = repoName || projectName;
  const destDir = path.join(OUTPUT_DIR, projectName);
  const octokit = new Octokit({ auth: token });
  const { data: user } = await octokit.rest.users.getAuthenticated();

  let repo;
  try {
    const created = await octokit.rest.repos.createForAuthenticatedUser({
      name: finalRepoName,
      description: description || "Generated by platform scaffolder.",
      private: !!isPrivate,
      auto_init: false,
    });
    repo = created.data;
  } catch (err) {
    if (err instanceof RequestError && err.status === 422) {
      throw new Error(`GitHub repo "${user.login}/${finalRepoName}" already exists. Pick a different name.`);
    }
    throw err;
  }

  const git = simpleGit(destDir);
  if (!(await fs.pathExists(path.join(destDir, ".git")))) {
    await git.init();
  }
  await git.addConfig("user.email", `${user.id}+${user.login}@users.noreply.github.com`, false, "local");
  await git.addConfig("user.name", user.login, false, "local");
  await git.add(".");
  await git.commit("Initial commit from platform scaffolder");
  await git.branch(["-M", "main"]);

  const authedUrl = repo.clone_url.replace(
    "https://",
    `https://x-access-token:${token}@`
  );
  const remotes = await git.getRemotes(true);
  if (remotes.find((remote) => remote.name === "origin")) {
    await git.removeRemote("origin");
  }
  await git.addRemote("origin", authedUrl);
  await git.push(["-u", "origin", "main"]);

  return {
    repoUrl: repo.html_url,
    cloneUrl: repo.clone_url,
    owner: user.login,
    repoName: finalRepoName,
  };
}

async function upsertVercelEnv({ projectIdOrName, token, teamId, key, value }) {
  return vercelFetch(`/v10/projects/${encodeURIComponent(projectIdOrName)}/env?upsert=true`, {
    method: "POST",
    token,
    teamId,
    body: {
      key,
      value,
      type: "encrypted",
      target: ["production", "preview", "development"],
      comment: "Generated by platform portal provisioning.",
    },
  });
}

async function deployGeneratedProject({ repoName, owner, env = {} }) {
  const token = process.env.VERCEL_TOKEN;
  const teamId = process.env.VERCEL_TEAM_ID || undefined;
  if (!token) {
    throw new Error("Server missing VERCEL_TOKEN. Set it in server/.env.");
  }

  const projectName = repoName.toLowerCase();
  let project;
  try {
    project = await vercelFetch("/v10/projects", {
      method: "POST",
      token,
      teamId,
      body: {
        name: projectName,
        framework: "vite",
        buildCommand: "npm run build",
        outputDirectory: "dist",
        installCommand: "npm install",
        devCommand: "npm run dev",
        gitRepository: {
          type: "github",
          repo: `${owner}/${repoName}`,
        },
      },
    });
  } catch (err) {
    if (err.status === 409 || /already exists/i.test(err.message || "")) {
      project = await vercelFetch(`/v9/projects/${projectName}`, { token, teamId });
    } else {
      throw err;
    }
  }

  for (const [key, value] of Object.entries(env)) {
    await upsertVercelEnv({
      projectIdOrName: project.id || project.name || projectName,
      token,
      teamId,
      key,
      value,
    });
  }

  const repoId = project?.link?.repoId;
  if (!repoId) {
    throw new Error("Vercel project has no linked GitHub repoId. Install or refresh the Vercel GitHub integration for this repo.");
  }

  const deployment = await vercelFetch("/v13/deployments", {
    method: "POST",
    token,
    teamId,
    body: {
      name: project.name,
      project: project.id,
      target: "production",
      gitSource: {
        type: "github",
        repoId,
        ref: "main",
      },
    },
  });

  const startedAt = Date.now();
  let final = deployment;
  let lastState = final.readyState || "QUEUED";
  while (Date.now() - startedAt < 120_000) {
    await delay(3000);
    final = await vercelFetch(`/v13/deployments/${deployment.id}`, { token, teamId });
    lastState = final.readyState || final.status || "UNKNOWN";
    if (lastState === "READY") break;
    if (lastState === "ERROR" || lastState === "CANCELED") {
      throw new Error(`Vercel build ${lastState}. Check the build logs.`);
    }
  }

  return {
    deploymentUrl: `https://${projectName}.vercel.app`,
    previewUrl: `https://${final.url || deployment.url}`,
    status: lastState,
  };
}

// ---------------------------------------------------------------------------
// POST /api/portal/provision
// Streams text/event-stream progress while provisioning Supabase, scaffolding,
// pushing to GitHub, and deploying to Vercel. Existing landing endpoints are
// intentionally untouched.
// ---------------------------------------------------------------------------
app.post("/api/portal/provision", async (req, res) => {
  const { templateId, projectName, portalConfig } = req.body || {};
  const resolvedTemplateId = validateResolvedTemplateId(templateId);
  const safeProjectName = safePortalSlug(projectName);

  if (!templateId || !resolvedTemplateId || !safeProjectName) {
    return res.status(400).json({
      success: false,
      error: "templateId and projectName are required and must be URL-safe.",
    });
  }

  const srcDir = path.join(TEMPLATES_DIR, resolvedTemplateId);
  const destDir = path.join(OUTPUT_DIR, safeProjectName);
  if (!(await fs.pathExists(srcDir))) {
    return res.status(404).json({
      success: false,
      error: `Template "${templateId}" not found in templates/.`,
    });
  }
  if (await fs.pathExists(destDir)) {
    return res.status(409).json({
      success: false,
      error: `Output "${safeProjectName}" already exists. Pick a different project name.`,
    });
  }

  const missingEnv = [];
  if (!process.env.SUPABASE_ACCESS_TOKEN) missingEnv.push("SUPABASE_ACCESS_TOKEN");
  if (!process.env.SUPABASE_ORG_ID && !process.env.SUPABASE_ORG_SLUG) {
    missingEnv.push("SUPABASE_ORG_ID");
  }
  if (!process.env.GITHUB_TOKEN) missingEnv.push("GITHUB_TOKEN");
  if (!process.env.VERCEL_TOKEN) missingEnv.push("VERCEL_TOKEN");
  if (missingEnv.length) {
    return res.status(500).json({
      success: false,
      error: `Missing server environment variables: ${missingEnv.join(", ")}`,
    });
  }

  let normalizedConfig;
  let usesStaticPortalAdminTemplate = false;
  let usesTopbarTemplate = false;
  let runtimeConfig;
  let readinessWarnings = [];
  try {
    normalizedConfig = normalizePortalConfig({
      ...(portalConfig || {}),
      templateId: resolvedTemplateId,
      slug: safeProjectName,
      portalName: portalConfig?.portalName || safeProjectName,
    });
    normalizedConfig.modules = normalizedConfig.modules.map((module) => ({
      ...module,
      tableName: tableNameForModule(module),
    }));
    usesStaticPortalAdminTemplate = await hasPortalAdminSupabaseTemplate(resolvedTemplateId);
    usesTopbarTemplate = resolvedTemplateId === TOPBAR_TEMPLATE_ID;
    runtimeConfig = usesStaticPortalAdminTemplate
      ? await buildPortalAdminRuntimeConfig(normalizedConfig)
      : usesTopbarTemplate
        ? buildTopbarRuntimeConfig(normalizedConfig)
        : normalizedConfig;
    const readiness = usesStaticPortalAdminTemplate
      ? auditPortalRuntimeConfig(runtimeConfig)
      : { errors: [], warnings: [] };
    if (readiness.errors.length) {
      throw new Error(readiness.errors.join(" "));
    }
    readinessWarnings = readiness.warnings;
  } catch (err) {
    const issues = err?.issues?.map((issue) => issue.message).join("; ");
    return res.status(400).json({
      success: false,
      error: issues || err.message || "Invalid portal config.",
    });
  }

  res.writeHead(200, {
    "Content-Type": "text/event-stream",
    "Cache-Control": "no-cache, no-transform",
    Connection: "keep-alive",
  });

  try {
    sendProgress(res, { step: 1, status: "running", message: "Creating database..." });
    const { project } = await createSupabaseProject(safeProjectName);
    const ref = project.ref || project.id;
    if (!ref) throw new Error("Supabase project response did not include a ref.");
    await waitForSupabaseHealthy(ref);
    const keys = await getSupabaseApiKeys(ref);
    sendProgress(res, { step: 1, status: "done", message: "Database ready." });

    sendProgress(res, { step: 2, status: "running", message: "Creating tables..." });
    if (isCrudPortalTemplate(resolvedTemplateId)) {
      await runSupabaseSql(ref, portalAdminSystemSchemaSql());
      await runSupabaseSql(ref, generateSQL(normalizedConfig));
    } else {
      await runSupabaseSql(ref, generateSQL(normalizedConfig));
    }
    sendProgress(res, { step: 2, status: "done", message: "Tables created." });

    // Refresh PostgREST schema cache now that PostgREST is healthy and listening,
    // so the new tables/columns are immediately queryable from the deployed portal.
    await reloadPostgrestSchema(ref);

    const adminEmail = DEFAULT_ADMIN_EMAIL;
    const adminPassword = DEFAULT_ADMIN_PASSWORD;
    sendProgress(res, { step: 3, status: "running", message: "Configuring authentication..." });
    const adminUser = await createSupabaseAdminUser({
      supabaseUrl: keys.supabaseUrl,
      serviceRoleKey: keys.serviceRoleKey,
      email: adminEmail,
      password: adminPassword,
    });
    sendProgress(res, { step: 3, status: "done", message: "Authentication configured." });

    sendProgress(res, { step: 4, status: "running", message: "Adding system-required data..." });
    await seedSystemRequiredData({
      ref,
      config: normalizedConfig,
      adminEmail,
      adminAuthUserId: adminUser?.id || adminUser?.user?.id || adminUser?.data?.id || "",
    });
    sendProgress(res, { step: 4, status: "done", message: "System data added. Business tables are empty." });

    sendProgress(res, { step: 5, status: "running", message: "Building portal from template..." });
    await copyPortalTemplate({
      templateId: resolvedTemplateId,
      projectName: safeProjectName,
      portalConfig: runtimeConfig,
    });
    sendProgress(res, { step: 5, status: "done", message: "Portal template ready." });

    sendProgress(res, { step: 6, status: "running", message: "Publishing to GitHub..." });
    const repo = await pushGeneratedProject({
      projectName: safeProjectName,
      repoName: safeProjectName,
      description: `${normalizedConfig.appName} generated portal`,
      isPrivate: true,
    });
    sendProgress(res, { step: 6, status: "done", message: "GitHub repository ready." });

    sendProgress(res, { step: 7, status: "running", message: "Deploying..." });
    const deployment = await deployGeneratedProject({
      repoName: repo.repoName,
      owner: repo.owner,
      env: {
        VITE_SUPABASE_URL: keys.supabaseUrl,
        VITE_SUPABASE_ANON_KEY: keys.anonKey,
      },
    });

    const basePortalAdminTables = [
      "organizations",
      "accounts",
      "organization_users",
      "payers",
      "patients",
      "patient_notes",
      "batches",
      "claims",
    ];
    const generatedTableNames = normalizedConfig.modules.map((module) => module.tableName);

    sendProgress(res, {
      step: 7,
      status: "complete",
      message: "Portal ready!",
      data: {
        liveUrl: deployment.deploymentUrl,
        repoUrl: repo.repoUrl,
        supabaseUrl: keys.supabaseUrl,
        supabaseProjectRef: ref,
        adminEmail,
        adminPassword,
        tables: usesStaticPortalAdminTemplate && normalizedConfig.industry === "healthcare"
          ? [...basePortalAdminTables, ...generatedTableNames]
          : generatedTableNames,
        sampleRowsPerTable: 0,
        sampleRowsPerGeneratedTable: 0,
        sampleDataSummary: "No business records seeded. Tables start empty except admin user, organization profile, and required system settings.",
        readinessWarnings,
        projectName: safeProjectName,
      },
    });
    res.end();
  } catch (err) {
    console.error("[portal/provision] error:", err);
    sendProgress(res, {
      status: "error",
      message: err.message || "Portal provisioning failed.",
      error: err.message || "Portal provisioning failed.",
    });
    res.end();
  }
});

